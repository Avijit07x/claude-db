export function isStopword(token: string): boolean {
  return STOPWORDS.has(token);
}

export function meaningfulTokens(text: string): string[] {
  return text
    .toLowerCase()
    .split(/[^\p{L}\p{N}_]+/u)
    .filter((token) => token.length > 1 && !isStopword(token));
}
